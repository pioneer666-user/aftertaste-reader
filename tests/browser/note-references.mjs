import assert from 'node:assert/strict';
import { cp, mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright';
import { build, repository } from '../fixtures/dependency-canvas.mjs';
import { createLoopReaderProject } from '../fixtures/loop-reader.mjs';
import { blockLink } from '../../dist/core/notes.js';

const root = path.join(repository, '.local', process.env.AFTERTASTE_TEST_TASK ?? 'D037/list-reference');
await mkdir(root, { recursive: true });
const run = await mkdtemp(path.join(root, 'references-')), project = path.join(run, 'project');
if (process.env.AFTERTASTE_READER_INPUT) await cp(process.env.AFTERTASTE_READER_INPUT, project, { recursive: true });
else {
  await createLoopReaderProject(project);
  await cp(new URL('../fixtures/page-preview/', import.meta.url), path.join(project, 'docs/aftertaste'), { recursive: true });
}
const file = path.join(project, 'docs/aftertaste/notes.json');
const disk = async () => JSON.parse(await readFile(file, 'utf8')).notes;
const original = await disk();
const { startReader } = await import(pathToFileURL(path.join(build, 'server/reader.js')));
const reader = await startReader(project, 0);
const report = { build, run, checks: [], errors: [] };
let browser;
try {
  browser = await chromium.launch({ channel: process.env.AFTERTASTE_BROWSER === 'chrome' ? 'chrome' : 'msedge' });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  page.setDefaultTimeout(6000);
  page.on('pageerror', error => report.errors.push(error.message));
  await page.goto(reader.url);
  await page.locator('#reader-navigation button[title="src/service.mjs"]').click();
  const text = '服务随后忽略这个返回值';
  const para = page.locator('#zhidif44 .explanation-text p').filter({ hasText: text });
  await para.scrollIntoViewIfNeeded();
  await para.evaluate((el, text) => {
    const node = el.firstChild, offset = node.textContent.indexOf(text);
    getSelection().setBaseAndExtent(node, offset, node, offset + text.length);
  }, text);
  await page.getByRole('button', { name: '加入笔记', exact: true }).click();
  const panel = page.locator('#quick-note'), input = panel.getByRole('textbox', { name: '笔记正文' });
  const saved = () => panel.getByRole('status').filter({ hasText: /^已保存$/u }).waitFor();
  const btn = name => panel.getByRole('button', { name, exact: true });
  const title = panel.getByRole('textbox', { name: '笔记标题（可选）' });
  const card = panel.locator('.cm-content .note-reference');
  const readClip = () => page.evaluate(() => navigator.clipboard.readText());
  const clip = value => page.evaluate(v => navigator.clipboard.writeText(v), value);
  const token = blockLink({ documentPath: 'docs/aftertaste/current/src/service.mjs.md', blockId: 'zhidif44', text });
  await card.getByText(text, { exact:true }).waitFor();
  await title.fill('审计问题');
  await btn('＋ 标签').click();
  await panel.getByRole('combobox', {name:'新标签'}).fill('审计');
  await btn('添加标签').click();
  await saved();
  assert.equal(await page.locator('[data-page=reader]').getAttribute('aria-current'), 'page');
  assert.deepEqual((await disk()).slice(0,-1), original);
  let note = (await disk()).at(-1);
  assert.equal(note.body, token + '\n\n'); assert.equal(note.title, '审计问题'); assert.deepEqual(note.tags, ['审计']);
  await card.click();
  await input.press('Control+c');
  assert.equal(await readClip(), token);
  await page.screenshot({ path: path.join(run, 'capture.png') });
  const grip = panel.locator('.quick-resize');
  const dragBy = async (dx, dy) => {
    const { x, y, width, height } = await grip.boundingBox();
    const startX = x + width / 2, startY = y + height / 2;
    await page.mouse.move(startX, startY);
    await page.mouse.down();
    await page.mouse.move(startX + dx, startY + dy, { steps: 5 });
    await page.mouse.up();
  };
  const initialBox = await panel.boundingBox();
  const initialBody = await panel.locator('.note-body-editor').boundingBox();
  await dragBy(-160, 120);
  const resized = await panel.boundingBox();
  assert.equal(resized.width, initialBox.width + 160);
  assert.equal(resized.height, initialBox.height + 120);
  assert.equal(resized.x + resized.width, initialBox.x + initialBox.width);
  assert.equal(resized.y, initialBox.y);
  assert.ok((await panel.locator('.note-body-editor').boundingBox()).height > initialBody.height + 110);
  await btn('预览').click();
  assert.deepEqual(await panel.boundingBox(), resized);
  await page.screenshot({ path: path.join(run, 'resized-preview.png') });
  await dragBy(-450, 880 - (resized.y + resized.height));
  const largest = await panel.boundingBox();
  assert.equal(largest.width, 900);
  assert.equal(largest.height, 800);
  await page.setViewportSize({ width: 290, height: 260 });
  const clipped = await panel.boundingBox();
  assert.equal(clipped.width, 274);
  assert.ok(clipped.y + clipped.height <= 260);
  assert.ok(clipped.height < 220);
  await page.setViewportSize({ width: 1440, height: 900 });
  await dragBy(710, -700);
  const smallest = await panel.boundingBox();
  assert.equal(smallest.width, 300);
  assert.equal(smallest.height, 220);
  await grip.press('ArrowLeft');
  await grip.press('ArrowDown');
  assert.equal((await panel.boundingBox()).width, 316);
  assert.equal((await panel.boundingBox()).height, 236);
  await btn('返回笔记列表').click();
  assert.equal((await panel.boundingBox()).height, 236);
  await btn('关闭随手记').click();
  await page.locator('.new-note').click();
  assert.equal((await panel.boundingBox()).width, 316);
  await grip.press('Home');
  assert.equal((await panel.boundingBox()).width, 380);
  assert.ok((await disk()).at(-1).revision === note.revision);
  report.resize = { initialBox, resized, largest, smallest, clipped };

  await panel.getByRole('searchbox').fill('审计问题');
  assert.equal(await panel.locator('.quick-list button').count(),1);
  await page.screenshot({ path: path.join(run,'list.png') });
  await btn('新建笔记').click();
  await title.fill('复制目标');
  await input.press('Control+v');
  await card.waitFor();
  await saved();
  assert.equal((await disk()).at(-1).body, token);
  await input.press('Control+End');
  await input.press('Backspace');
  await card.waitFor({state:'detached'});
  await saved();
  assert.equal((await disk()).at(-1).body, '');
  await input.press('Control+z');
  await card.waitFor();
  await card.click();
  await input.press('Control+x');
  assert.equal(await readClip(),token);
  await card.waitFor({state:'detached'});
  await input.press('Control+v');
  await card.waitFor();
  await input.press('Control+Home');
  await input.press('Delete');
  await card.waitFor({state:'detached'});
  await saved();
  assert.equal((await disk()).at(-1).body,'');
  const special = blockLink({documentPath:'docs/aftertaste/current/src/中文 (a).mjs.md',blockId:'zhidif44',text:'原文 [x] & <字>\n😀'});
  const ordinary = '[普通链接](' + special.slice(special.indexOf('](<') + 3, -2) + ')';
  const prefix = ordinary + ' 前文 ';
  await clip(prefix + special + ' 后文');
  await input.press('Control+v');
  await card.getByText('原文 [x] & <字> 😀').waitFor();
  await card.click();
  await page.keyboard.insertText('替换');
  await saved();
  assert.equal((await disk()).at(-1).body,prefix + '替换 后文');
  await input.press('Control+z');
  await card.waitFor();
  await saved();
  assert.equal((await disk()).at(-1).body,prefix + special + ' 后文');
  await btn('预览').click();
  assert.equal(await panel.getByRole('link', {name:'普通链接'}).getAttribute('data-note-raw'), null);
  const link = panel.locator('a[data-note-raw]');
  await link.evaluate(a => { const n=a.firstChild; getSelection().setBaseAndExtent(n,1,n,2); });
  await page.keyboard.press('Control+c');
  assert.equal(await readClip(),special);
  await btn('关闭随手记').click();
  await page.locator('[data-page=notes]').click();
  const bench=page.locator('#notes');
  await bench.locator('.note-list button').filter({hasText:'复制目标'}).click();
  await bench.getByRole('button',{name:'编辑',exact:true}).click();
  const benchInput = bench.getByRole('textbox',{name:'笔记正文'});
  await bench.locator('.note-reference').click();
  await benchInput.press('Control+c');
  assert.equal(await readClip(),special);
  await benchInput.press('Delete');
  await bench.getByRole('status').filter({hasText:/^已保存$/u}).waitFor();
  assert.equal((await disk()).at(-1).body,prefix + ' 后文');
  await page.reload();
  await page.setViewportSize({width:390,height:844});
  await page.locator('.new-note').click();
  await panel.getByRole('searchbox').fill('审计问题');
  await panel.locator('.quick-list button').click();
  assert.equal(await title.inputValue(),'审计问题');
  await btn('移除标签 审计').click();
  await title.fill('重命名后');
  await saved();
  assert.deepEqual((await disk()).find(n=>n.id===note.id).tags,[]);
  await page.screenshot({path:path.join(run,'narrow-edit.png')});
  assert.deepEqual((await disk()).slice(0,original.length),original);
  assert.equal((await disk()).length,original.length+2);
  report.checks.push('原页捕获、命名、标签、搜索、重开已有篇、双向整删/撤销、跨笔记原格式剪贴、预览复制与工作台一致，原记录完整');
  assert.deepEqual(report.errors,[]);
  await context.close();
  const touch = await browser.newContext({ viewport: { width: 390, height: 760 }, hasTouch: true, isMobile: true });
  const mobile = await touch.newPage();
  await mobile.goto(reader.url);
  await mobile.locator('.new-note').tap();
  const mobilePanel = mobile.locator('#quick-note'), handle = mobilePanel.locator('.quick-resize');
  await mobilePanel.locator('.quick-list button').first().waitFor();
  const touchStart = await mobilePanel.boundingBox(), handleBox = await handle.boundingBox();
  assert.ok(handleBox.width >= 44 && handleBox.height >= 44);
  const client = await touch.newCDPSession(mobile);
  const finger = { x: handleBox.x + 22, y: handleBox.y + 22 };
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [finger] });
  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: finger.x + 52, y: finger.y + 74 }] });
  await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  const touchEnd = await mobilePanel.boundingBox();
  assert.ok(Math.abs(touchEnd.width - (touchStart.width - 52)) < 1);
  assert.ok(Math.abs(touchEnd.height - (touchStart.height + 74)) < 1);
  report.resize.touch = { touchStart, touchEnd, handleBox };
  await touch.close();
} catch(error) { report.failure=error.stack; throw error; }
finally { await browser?.close(); await reader.server.close(); await writeFile(path.join(run,'report.json'),JSON.stringify(report,null,2)); console.log(run); }
