import { startTestReader, openReader } from '../fixtures/reader-session.mjs';
import assert from 'node:assert/strict';
import { cp, mkdir, mkdtemp, readFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium, firefox } from 'playwright';
import { build, repository } from '../fixtures/dependency-canvas.mjs';
import { readJSON, writeJSON } from '../fixtures/dependency-legends.mjs';
import { createExampleProject, exampleId, examples } from '../fixtures/loop-examples.mjs';

const base = path.join(repository, '.local/D054');
await mkdir(base, { recursive: true });
const run = await mkdtemp(path.join(base, 'browser-'));
const project = path.join(run, 'project');
if (process.env.AFTERTASTE_TRIAL_PROJECT) await cp(process.env.AFTERTASTE_TRIAL_PROJECT, project, { recursive: true });
else await createExampleProject(project);
const reader = await startTestReader(project, 0);
let browser;
try {
  const engine = process.env.AFTERTASTE_BROWSER ?? 'msedge';
  browser = engine === 'firefox' ? await firefox.launch() : await chromium.launch({ channel: engine });
  console.log(engine, browser.version(), run);
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(8000);
  const errors = [], writes = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (r.method() === 'PUT') writes.push(r.url()); });
  const loop = page.locator('.loop-canvas:visible');
  const picker = loop.locator('.canvas-rail').getByRole('button', { name: '示例路线', exact: true });
  const choices = loop.locator('.example-panel:popover-open');
  const pick = async name => {
    await picker.click();
    await choices.getByRole('button', { name: name || '查看全图' }).click();
    await choices.waitFor({ state: 'hidden' });
  };
  const question = loop.locator('[data-legend=outcomes]');
  const loopHash = '#aftertaste-loop/' + exampleId + '/check';
  const modelDir = path.join(project, 'docs/aftertaste/loops', exampleId);
  const layout = path.join(modelDir, 'layout.json');
  const model = path.join(modelDir, 'current/loop.json');
  const go = async hash => { await page.goto('about:blank'); await openReader(page, reader.url + hash); };
  const view = () => loop.locator('.vue-flow__transformationpane').evaluate(el => el.style.transform);
  const steps = () => loop.locator('[data-step]').evaluateAll(els => els.map(el => el.dataset.step).sort());
  const saved = async action => {
    const [response] = await Promise.all([page.waitForResponse(r => r.request().method() === 'PUT'), action()]);
    assert.equal(response.status(), 200);
  };
  const edge = (from, to) => loop.locator('[data-edge="file:' + from + '→file:' + to + '"]');
  const route = async index => {
    const ids = examples[index]?.steps ?? [];
    const inks = ids.slice(1).map((to, i) => 'file:' + ids[i] + '→file:' + to);
    await page.waitForFunction(({ nodes, edges }) => {
      const el = document.querySelector('.loop-canvas:not([style*="display: none"])');
      const keys = (attr, key) => [...el.querySelectorAll(attr)].map(node => node.dataset[key]).sort().join('|');
      return keys('[data-step][data-route-member]', 'step') === nodes && keys('[data-route-edge]', 'edge') === edges &&
        el.querySelectorAll('.route-band').length === (edges ? edges.split('|').length : 0);
    }, { nodes: [...ids].sort().join('|'), edges: inks.sort().join('|') });
  };
  await go(loopHash);
  await picker.waitFor();
  await loop.locator('[data-reading-step=check]').waitFor();
  const initial = await view(), original = await readFile(layout);
  const startWrites = writes.length;
  assert.equal(await picker.getAttribute('data-active'), null);
  await picker.click();
  assert.ok(await choices.getByRole('button', { name: examples[0].name }).isVisible());
  assert.match(await choices.innerText(), /建单时集合仍为空/u);
  await page.setViewportSize({ width: 1000, height: 650 });
  const bounds = await choices.boundingBox(), icon = await picker.boundingBox();
  assert.ok(bounds.x >= icon.x + icon.width && bounds.y >= 0 && bounds.x + bounds.width <= 1000 && bounds.y + bounds.height <= 650);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: path.join(run, 'route-menu.png') });
  await choices.getByRole('button', { name: '查看全图' }).press('Escape');
  assert.equal(await picker.evaluate(el => el === document.activeElement), true);
  await picker.click();
  await loop.locator('.loop-step-heading').click();
  await choices.waitFor({ state: 'hidden' });
  assert.deepEqual(await steps(), ['build', 'check']);
  await pick(examples[0].name);
  await route(0);
  assert.deepEqual(await steps(), ['append', 'build', 'check']);
  assert.equal(await question.getAttribute('aria-expanded'), 'false');
  assert.equal(await loop.locator('.example-caption').innerText(), examples[0].name);
  assert.equal(await picker.getAttribute('data-active'), 'true');
  await page.screenshot({ path: path.join(run, 'success.png') });
  await loop.locator('[data-step=build]').click();
  await loop.locator('.loop-source-trigger').click();
  const source = page.locator('.loop-source-panel:visible');
  assert.match(await source.innerText(), /orders.length/u);
  await source.getByRole('button').click();
  await loop.locator('.loop-reader-toggle').click();
  await loop.locator('.loop-reader-toggle').click();
  await route(0);
  await picker.press('Enter');
  const first = choices.getByRole('button', { name: examples[0].name });
  assert.equal(await first.evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('ArrowDown');
  assert.equal(await choices.getByRole('button', { name: examples[1].name }).evaluate(el => el === document.activeElement), true);
  await page.keyboard.press('Enter');
  await route(1);
  assert.deepEqual(await steps(), ['build', 'check', 'reject']);
  assert.ok(await loop.locator('[data-reading-step=build]').isVisible());
  await picker.press('Space');
  await choices.getByRole('button', { name: examples[1].name }).press('End');
  await page.keyboard.press('Enter');
  await route(-1);
  assert.equal(await view(), initial);
  assert.deepEqual(await readFile(layout), original);
  assert.equal(writes.length, startWrites);
  await pick(examples[0].name);
  await saved(() => question.press('Enter'));
  await route(0);
  assert.deepEqual(await steps(), ['append', 'build', 'check', 'reject']);
  await loop.locator('[data-step=check]').click();
  await edge('check', 'reject').press('Enter');
  assert.match(await loop.locator('.edge-reason').innerText(), /4.5/u);
  await route(0);
  await edge('check', 'reject').press('Escape');
  await page.locator('[popovertarget=reader-theme-menu]').click();
  await page.locator('[data-theme-choice=black]').click();
  await pick(examples[1].name);
  await route(1);
  const glow = await loop.locator('.route-band').evaluate(el => getComputedStyle(el).filter);
  assert.match(glow, /blur/);
  const surface = loop.locator('[data-step=reject]');
  assert.notEqual(await surface.evaluate(el => getComputedStyle(el).boxShadow), 'none');
  assert.equal(await loop.locator('marker').evaluateAll(markers => markers.every(m => m.getAttribute('markerUnits') === 'userSpaceOnUse')), true);
  const fork = await loop.locator('.foreground-edges > g:not(.edge-label)').evaluateAll(groups => groups.map(g => {
    const stroke = g.querySelector('path:last-of-type'), style = getComputedStyle(stroke);
    return { route: !!g.querySelector('.route-band'), width: parseFloat(style.strokeWidth), color: style.stroke,
      arrow: stroke.getAttribute('marker-end'), library: stroke.classList.contains('library-use') };
  }));
  const traveled = fork.find(item => item.route);
  const other = fork.find(item => !item.route && !item.library);
  assert.ok(traveled.width > other.width && traveled.color !== other.color && traveled.arrow && other.arrow);
  assert.notEqual(await loop.locator('.library-use-edge .vue-flow__edge-path').first().evaluate(el => getComputedStyle(el).strokeDasharray), 'none');
  assert.ok(await loop.locator('.edge-label text').allTextContents().then(labels => labels.includes('非整数，抛错')));
  await page.screenshot({ path: path.join(run, 'fork-dark.png') });
  await picker.press('Tab');
  await edge('check', 'build').focus();
  await loop.locator('.edge-focus-ring').waitFor({ state: 'attached' });
  const box = await loop.locator('[data-step=reject]').boundingBox();
  await saved(async () => {
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 36, box.y + box.height / 2 + 19, { steps: 8 });
    await page.mouse.up();
  });
  const moved = await readJSON(layout);
  assert.notDeepEqual(moved.layout.positions.reject, JSON.parse(original).layout.positions.reject);
  const afterDrag = writes.length;
  for (const name of [examples[0].name, examples[1].name, '']) await pick(name);
  await route(-1);
  assert.equal(writes.length, afterDrag);
  assert.deepEqual(await readJSON(layout), moved);
  assert.equal(await question.getAttribute('aria-expanded'), 'true');

  await go('#canvas-reading');
  const dep = page.locator('#canvas-reading'), actions = dep.locator('.route-actions');
  const choose = async id => {
    await page.locator('.reader-navigation-toggle').press('Enter');
    await page.locator('#loop-navigation [data-loop="' + id + '"]').press('Enter');
  };
  assert.equal(await dep.locator('.example-tool').count(), 0);
  const members = () => dep.locator('[data-route-member]').evaluateAll(els => els.map(el => el.dataset.file).sort());
  await choose(exampleId);
  await dep.locator('[data-route-member]').first().waitFor();
  await dep.locator('[data-file="src/service.mjs"]').click();
  assert.deepEqual(await members(), ['src/rules.mjs', 'src/service.mjs']);
  const dependencyEdge = dep.locator('[data-edge="file:src%2Frules.mjs→file:src%2Fservice.mjs"]');
  assert.notEqual(await dep.locator('[data-route-member] .card-surface').first().evaluate(el => getComputedStyle(el).filter), 'none');
  await dependencyEdge.press('Enter');
  assert.match(await dep.locator('.edge-reason').innerText(), /数量/u);
  assert.equal(await dep.locator('[data-route-edge],.route-band').count(), 0);
  await page.screenshot({ path: path.join(run, 'dependency.png') });
  await actions.getByRole('button', { name: '阅读此闭环' }).click();
  await pick(examples[0].name);
  await page.getByRole('button', { name: '后退', exact: true }).click();
  await dep.locator('.edge-reason').waitFor();
  await actions.getByRole('button', { name: '阅读此闭环' }).waitFor();
  assert.deepEqual(await members(), ['src/rules.mjs', 'src/service.mjs']);
  await actions.getByRole('button', { name: '清除高亮' }).click();
  assert.deepEqual(await members(), []);

  // Synthetic shortcut in a disposable copy distinguishes traversed edges from pairs of participating nodes.
  const candidate = await readJSON(model);
  candidate.edges.push({ from: 'check', to: 'append', reason: '仅用于区分端点和实走边的测试连线。' });
  candidate.legends.find(e => e.id === 'outcomes').edges.push({ from: 'check', to: 'build' });
  await writeJSON(model, candidate);
  await go(loopHash);
  await saved(() => question.click());
  await pick(examples[0].name);
  await route(0);
  await edge('check', 'append').waitFor({ state: 'attached' });
  assert.equal(await edge('check', 'append').getAttribute('data-route-edge'), null);
  await pick('');
  assert.equal(await edge('check', 'build').count(), 0);
  await pick(examples[1].name);
  await choose('quantity-outcomes');
  await page.locator('#loop-canvas-quantity-outcomes-reading:visible [data-step=check]').waitFor();
  assert.equal(await picker.count(), 0);
  const graphFile = path.join(project, 'docs/aftertaste/dependency-graph.json');
  const graph = await readJSON(graphFile);
  graph.source_commit = 'a'.repeat(40);
  await writeJSON(graphFile, graph);
  await go('#canvas-reading'); await choose(exampleId);
  await actions.getByRole('status').filter({ hasText: '源码版本不同' }).waitFor();
  assert.deepEqual(await members(), []);
  await actions.getByRole('button', { name: '阅读此闭环' }).click();
  await pick(examples[0].name);
  await route(0);
  assert.deepEqual(errors, []);
  console.log('两图示例路线、固定源码、问句、布局及版本边界通过');
} catch (error) {
  await browser?.contexts()[0]?.pages()[0]?.screenshot({ path: path.join(run, 'failure.png') });
  throw error;
} finally {
  await browser?.close();
  await reader.server.close();
}
