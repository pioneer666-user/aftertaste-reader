import { startTestReader, openReader } from '../fixtures/reader-session.mjs';
import assert from 'node:assert/strict';
import { cp, mkdir, mkdtemp, readFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium, firefox } from 'playwright';
import { applyGraphUpdate, repository } from '../fixtures/dependency-canvas.mjs';
import { readJSON, writeJSON } from '../fixtures/dependency-legends.mjs';
import { createSwitchProject, loopId } from '../fixtures/switch-legends.mjs';

const base = path.join(repository, '.local/D053');
await mkdir(base, { recursive: true });
const run = await mkdtemp(path.join(base, 'browser-'));
const project = path.join(run, 'project');
if (process.env.AFTERTASTE_SWITCH_PROJECT) await cp(process.env.AFTERTASTE_SWITCH_PROJECT, project, { recursive: true });
else await createSwitchProject(project);
const reader = await startTestReader(project, 0);
let browser;
try {
  const engine = process.env.AFTERTASTE_BROWSER ?? 'msedge';
  browser = engine === 'firefox' ? await firefox.launch() : await chromium.launch({ channel: engine });
  console.log(engine, browser.version(), run);
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(6500);
  const go = async hash => { await page.goto('about:blank'); await openReader(page, reader.url + '/#' + hash); };
  const loop = 'aftertaste-loop/' + loopId + '/';
  const graph = page.locator('.loop-canvas:visible,.dependency-canvas:visible').last();
  const question = graph.locator('.switch-question');
  const direction = side => graph.locator('[data-direction="' + side + '"]');
  const back = graph.locator('.switch-return');
  const shot = name => page.screenshot({ path: path.join(run, name + '.png') });
  const view = () => graph.locator('.vue-flow__transformationpane').evaluate(el => el.style.transform);
  const layoutPath = path.join(project, 'docs/aftertaste/loops', loopId, 'layout.json');
  const dependencyPath = path.join(project, 'docs/aftertaste/dependency-layout.json');
  const graphPath = path.join(project, 'docs/aftertaste/dependency-graph.json');
  const graphBytes = await readFile(graphPath);
  const seed = await readJSON(layoutPath);
  const saved = async action => {
    const [response] = await Promise.all([page.waitForResponse(r => r.request().method() === 'PUT'), action()]);
    assert.equal(response.status(), 200, await response.text());
  };
  const drag = async (x, y, dx, dy) => {
    await page.mouse.move(x, y); await page.mouse.down();
    await page.mouse.move(x + dx, y + dy, { steps: 12 }); await page.mouse.up();
  };
  const dragNode = async (target, dx, dy) => {
    const rect = await target.boundingBox();
    assert.ok(rect);
    await drag(rect.x + rect.width / 2, rect.y + rect.height / 2, dx, dy);
  };
  await go(loop + 'check');
  await question.waitFor();
  assert.match(await question.innerText(), /展开 2 步/u);
  assert.equal(await graph.locator('[data-step=reject]').count(), 0);
  const initial = await view();
  for (const keyboard of [false, true]) {
    const activate = el => keyboard ? el.press('Enter') : el.click();
    await saved(() => activate(question));
    await direction('Right').waitFor();
    assert.equal(await direction('Right').innerText(), '右侧还有 1 步 →');
    assert.equal(await view(), initial);
    assert.equal(await graph.locator('.loop-step[data-reading-step=check]').count(), 1);
    if (!keyboard) await shot('loop-right');
    await saved(() => activate(direction('Right')));
    await back.waitFor();
    assert.notEqual(await view(), initial);
    await saved(() => activate(back));
    assert.equal(await view(), initial);
    assert.equal(await question.evaluate(el => document.activeElement === el), true);
    await saved(() => activate(question));
    assert.equal(await direction('Right').count(), 0);
  }
  await saved(() => dragNode(question, 55, -35));
  assert.equal(await question.getAttribute('aria-expanded'), 'false');
  const moved = await readJSON(layoutPath);
  assert.notDeepEqual(moved.layout.positions['legend:outcomes'], seed.layout.positions['legend:outcomes']);
  assert.deepEqual(moved.layout.positions.reject, seed.layout.positions.reject);
  assert.deepEqual(moved.layout.positions.append, seed.layout.positions.append);
  await go(loop + 'reject');
  await graph.locator('[data-reading-step=reject]').waitFor();
  assert.equal(await question.getAttribute('aria-expanded'), 'true');
  await graph.locator('.loop-source-trigger').click();
  assert.match(await page.locator('.loop-source-panel:visible').innerText(), /Number.isInteger/u);
  await saved(() => question.click());
  assert.equal(await graph.locator('[data-step=reject]').count(), 0);
  assert.ok(await page.locator('.loop-source-panel:visible').isVisible());

  // Reopen isolated, hand-placed layouts to check each edge of the readable region.
  for (const [side, point] of [['Left', { x: -1000, y: 155 }], ['Top', { x: 410, y: -900 }], ['Bottom', { x: 410, y: 1400 }]]) {
    await page.goto('about:blank');
    await writeJSON(layoutPath, { ...moved, layout: { ...moved.layout, positions: { ...moved.layout.positions, append: point } } });
    await go(loop + 'check');
    await saved(() => question.click());
    await direction(side).waitFor();
    assert.equal(await graph.locator('[data-direction]').count(), 1);
    await saved(() => direction(side).press('Space'));
    await saved(() => back.press('Enter'));
  }
  await page.goto('about:blank');
  const nearReader = { ...moved, layout: { ...moved.layout, positions: { ...moved.layout.positions, append: { x: 970, y: 150 } } } };
  await writeJSON(layoutPath, nearReader);
  await go(loop + 'check');
  await saved(() => question.click());
  await direction('Right').waitFor();
  const panelToggle = graph.locator('.loop-reader-toggle');
  await panelToggle.click();
  await direction('Right').waitFor({ state: 'detached' });
  await page.setViewportSize({ width: 1000, height: 800 });
  await direction('Right').waitFor();
  await saved(() => graph.getByRole('button', { name: '缩小画布', exact: true }).click());
  await direction('Right').waitFor({ state: 'detached' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await go('canvas-reading');
  const files = () => graph.locator('[data-file]').evaluateAll(items => items.map(e => [e.dataset.file, e.closest('.vue-flow__node').style.transform]));
  await question.waitFor();
  const before = await files();
  const audit = graph.locator('[data-edge="file:support%2Faudit.mjs→file:src%2Fservice.mjs"]');
  assert.equal(await audit.count(), 0);
  assert.match(await question.innerText(), /展开 1 条关系/u);
  await saved(() => question.click());
  await audit.waitFor({ state: 'attached' });
  const ink = audit.locator('.vue-flow__edge-path');
  const opacity = () => ink.evaluate(el => Number(getComputedStyle(el).opacity));
  await page.waitForFunction(() => {
    const path = document.querySelector('.edge-ink.switch-pulse .vue-flow__edge-path');
    return path && Number(getComputedStyle(path).opacity) > .95;
  });
  await graph.locator('.edge-ink.switch-pulse').waitFor({ state: 'detached' });
  assert.ok(await opacity() < .2);
  assert.deepEqual(await files(), before);
  assert.equal(await graph.locator('[data-direction]').count(), 0);
  await audit.press('Enter');
  assert.match(await graph.locator('.edge-details').innerText(), /新编号/u);
  await graph.locator('.edge-details button').click();
  await page.locator('[popovertarget=reader-theme-menu]').click();
  await page.locator('[data-theme-choice=black]').click();
  await question.focus(); await page.keyboard.press('Tab'); await page.keyboard.press('Shift+Tab');
  await shot('dependency-dark');
  assert.ok(await question.evaluate(el => el.matches(':focus-visible') && getComputedStyle(el).outlineStyle !== 'none'));
  await saved(() => dragNode(question, 15, -12));
  await saved(() => dragNode(graph.locator('[data-legend=zod]'), 12, 18));
  const bounds = await Promise.all([question.boundingBox(), graph.locator('[data-legend=zod]').boundingBox()]);
  const left = Math.min(...bounds.map(b => b.x)) - 7, top = Math.min(...bounds.map(b => b.y)) - 7;
  const right = Math.max(...bounds.map(b => b.x + b.width)) + 7, bottom = Math.max(...bounds.map(b => b.y + b.height)) + 7;
  await page.keyboard.down('Control');
  await drag(left, top, right - left, bottom - top);
  await page.keyboard.up('Control');
  await page.keyboard.press('Control+g');
  await graph.locator('#canvas-selection-name').fill('审计与类型');
  await saved(() => graph.locator('#canvas-selection-name').press('Enter'));
  const dep = await readJSON(dependencyPath);
  assert.deepEqual(dep.layout.groups.find(g => g.name === '审计与类型').members.sort(), ['legend:audit-trail','legend:zod']);
  await go(loop + 'check'); await question.waitFor();
  assert.match(await question.innerText(), /收起 2 步/u);
  await go('canvas-reading'); await question.waitFor();
  assert.equal(await question.getAttribute('aria-expanded'), 'true');
  assert.ok(await graph.locator('.group-handle').filter({ hasText: '审计与类型' }).isVisible());
  await saved(() => question.click());
  assert.equal(await audit.count(), 0);
  assert.deepEqual(await readFile(graphPath), graphBytes);
  // The only controlled relation can also be entirely outside the viewport.
  await page.goto('about:blank');
  const offscreen = await readJSON(dependencyPath);
  for (const id of ['support/audit.mjs', 'src/service.mjs']) offscreen.layout.positions[id].x += 1900;
  await writeJSON(dependencyPath, offscreen);
  await go('canvas-reading');
  await saved(() => question.press('Space'));
  await direction('Right').waitFor();
  assert.match(await direction('Right').innerText(), /1 条关系/u);
  await saved(() => direction('Right').click());
  await audit.press('Enter');
  assert.match(await graph.locator('.edge-details').innerText(), /新编号/u);
  await saved(() => back.press('Enter'));
  await page.goto('about:blank');
  const original = await readJSON(graphPath);
  const shared = { type: 'switch', id: 'shared-file', question: '查看入口文件？', nodes: ['src/api.mjs'], edges: [] };
  const mixed = { ...shared, id: 'audit-detail', question: '入口与审计如何配合？',
    edges: [{ from: 'support/audit.mjs', to: 'src/service.mjs' }] };
  await applyGraphUpdate({ projectRoot: project, commit: original.source_commit }, { legendUpserts: [shared, mixed] });
  const combined = await readJSON(dependencyPath);
  combined.layout.expanded = [];
  Object.assign(combined.layout.positions, { 'legend:shared-file': { x: 360, y: 570 },
    'legend:audit-detail': { x: 640, y: 540 }, 'legend:audit-trail': { x: 2420, y: 460 } });
  await writeJSON(dependencyPath, combined);
  await go('canvas-reading');
  const a = graph.locator('[data-legend=shared-file]'), b = graph.locator('[data-legend=audit-detail]');
  await saved(() => a.click());
  assert.match(await b.innerText(), /展开 1 条关系/u);
  const sourceView = await view();
  await saved(() => b.click());
  assert.match(await direction('Right').innerText(), /1 条关系/u);
  await saved(() => direction('Right').click());
  const third = graph.locator('[data-legend=audit-trail]');
  await saved(() => third.click());
  await saved(() => third.press('Space'));
  assert.ok(await back.isVisible());
  await saved(() => back.press('Enter'));
  assert.equal(await view(), sourceView);
  assert.ok(await b.evaluate(el => document.activeElement === el));
  await page.setViewportSize({ width: 390, height: 780 }); await go(loop + 'check');
  await graph.locator('[data-reading-step=check]').waitFor();
  assert.ok(await graph.locator('.loop-step-heading').isVisible());
  await shot('narrow-reading');
  assert.deepEqual(errors, []);
  console.log('双图显隐、定位返回、拖动、分组、持久化、深链与窄窗通过');
} catch (error) {
  const page = browser?.contexts()[0]?.pages()[0];
  if (page) await page.screenshot({ path: path.join(run, 'failure.png') });
  throw error;
} finally {
  await browser?.close();
  await reader.server.close();
}
